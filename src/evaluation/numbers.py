"""Emit ``paper/numbers.tex``: every inline number the manuscript quotes.

The paper never hard-codes a result. It uses macros such as ``\\NMOPearson``
that are defined here from the run artifacts, so prose and experiments cannot
diverge. If a run is missing, the macro expands to a visible ``??`` rather than
to a stale value.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from .tables import load_json_glob


def _ms(df: pd.DataFrame, key: str) -> str:
    if df.empty or key not in df.columns:
        return r"\textbf{??}"
    m, s = df[key].mean(), df[key].std()
    return f"{m:.3f}" + (f"\\,$\\pm$\\,{s:.3f}" if np.isfinite(s) and s > 0 else "")


def _val(x: Optional[float], prec: int = 3) -> str:
    return r"\textbf{??}" if x is None or not np.isfinite(x) else f"{x:.{prec}f}"


def build(results_root: str | Path = "results", out: str | Path = "paper/numbers.tex",
          processed_summary: str | Path = "data/processed/SUMMARY.json") -> Path:
    results_root = Path(results_root)
    L: List[str] = [
        "% Auto-generated by src/evaluation/numbers.py -- do not edit by hand.",
        r"\providecommand{\NA}{\textbf{??}}",
    ]

    def cmd(name: str, value: str):
        L.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    # ---- Experiment 1 : main benchmark ---------------------------------- #
    e1 = pd.DataFrame([r for r in load_json_glob("exp1/**/*.json", results_root)
                       if "model" in r and "pearson_mean" in r])
    if not e1.empty:
        nmo = e1[e1["model"] == "nmo"]
        base = e1[e1["model"] != "nmo"]
        cmd("NMOPearson", _ms(nmo, "pearson_mean"))
        cmd("NMORMSE", _ms(nmo, "rmse"))
        cmd("NMOSSIM", _ms(nmo, "ssim_mean"))
        cmd("NMOMoran", _ms(nmo, "morans_i_abs_error"))
        cmd("NMOParams", f"{nmo['n_params'].mean()/1e6:.2f}M" if "n_params" in nmo else r"\NA")
        cmd("NSeeds", str(int(e1.groupby("model").size().max())))
        if not base.empty:
            g = base.groupby("model")["pearson_mean"].mean().sort_values(ascending=False)
            best_name, best_val = g.index[0], float(g.iloc[0])
            bb = base[base["model"] == best_name]
            cmd("BestBaseline", best_name.replace("_", " "))
            cmd("BestBaselinePearson", _ms(bb, "pearson_mean"))
            cmd("BestBaselineMoran", _ms(bb, "morans_i_abs_error"))
            nv = float(nmo["pearson_mean"].mean()) if not nmo.empty else np.nan
            cmd("PearsonGain", _val(nv - best_val))
            cmd("PearsonGainPct", _val(100 * (nv - best_val) / max(best_val, 1e-9), 1))
        # honest read-out of the over-smoothing diagnostic
        if "morans_i_pred" in e1.columns:
            cmd("NMOMoranPred", _ms(nmo, "morans_i_pred"))
            cmd("MoranTrue", _ms(nmo, "morans_i_true"))

    # ---- Experiment 2 / 3 : transfer ------------------------------------ #
    for tag, pat in [("Tissue", "exp2/*.json"), ("Res", "exp3/*.json")]:
        df = pd.DataFrame([r for r in load_json_glob(pat, results_root) if "setting" in r])
        if df.empty:
            continue
        for setting, suffix in [("zero_shot", "ZeroShot"), ("oracle", "Oracle"),
                                ("floor", "Floor"), ("decoder_finetune", "FineTune")]:
            sub = df[(df["setting"] == setting) & (df["model"].isin(["nmo", "mean"]))]
            if not sub.empty:
                cmd(f"{tag}{suffix}", _ms(sub, "pearson_mean"))
        zs = df[(df["setting"] == "zero_shot")]
        if not zs.empty:
            g = zs.groupby("model")["pearson_mean"].mean().sort_values(ascending=False)
            cmd(f"{tag}ZeroShotBest", str(g.index[0]).replace("_", " "))
        if "n_shared_genes" in df.columns:
            cmd(f"{tag}SharedGenes", str(int(df["n_shared_genes"].iloc[0])))

    # ---- Experiment 5 : ablations --------------------------------------- #
    e5 = pd.DataFrame([r for r in load_json_glob("exp5/*.json", results_root) if "variant" in r])
    if not e5.empty:
        g = e5.groupby("variant")["pearson_mean"].agg(["mean", "std"])
        full = float(g.loc["full", "mean"]) if "full" in g.index else np.nan
        cmd("AblFull", _val(full))
        for v, name in [("no_dynamics", "AblNoDynamics"), ("no_diffusion", "AblNoDiffusion"),
                        ("no_reaction", "AblNoReaction"), ("no_pde", "AblNoPDE"),
                        ("no_bio_reg", "AblNoBioReg"),
                        ("isotropic_diffusion", "AblIsotropic"),
                        ("discrete_gnn", "AblDiscreteGNN")]:
            if v in g.index:
                cmd(name, _val(float(g.loc[v, "mean"])))
                cmd(name + "Delta", _val(float(g.loc[v, "mean"]) - full))

    # ---- physics diagnostics -------------------------------------------- #
    phys = []
    for p in sorted(results_root.glob("**/result.json")):
        try:
            r = json.loads(p.read_text())
            if "physics" in r:
                phys.append(r["physics"])
        except Exception:
            continue
    if phys:
        dl = np.concatenate([np.asarray(p["diffusion_length_um"]).ravel() for p in phys
                             if p.get("diffusion_length_um")])
        if dl.size:
            cmd("DiffLenMedian", f"{np.median(dl):.0f}")
            cmd("DiffLenLo", f"{np.percentile(dl, 10):.0f}")
            cmd("DiffLenHi", f"{np.percentile(dl, 90):.0f}")
        wl = [p["pattern_wavelength_um"] for p in phys if p.get("pattern_wavelength_um")]
        cmd("TuringFrac", f"{100*np.mean([bool(p['turing_unstable']) for p in phys]):.0f}")
        if wl:
            cmd("PatternWavelength", f"{np.median(wl):.0f}")

    # ---- Experiment 4 ---------------------------------------------------- #
    bead = pd.DataFrame(load_json_glob("exp4/bead_implant.json", results_root))
    if not bead.empty:
        sig = bead.groupby("pathway")["p_value"].mean()
        cmd("BeadNSig", str(int((sig < 0.05).sum())))
        cmd("BeadNPathways", str(int(len(sig))))
        cmd("BeadWidth", f"{bead['response_halfwidth_um'].mean():.0f}")
    ps = pd.DataFrame([r for r in load_json_glob("exp4/perturbseq_consistency.json", results_root)
                       if "error" not in r])
    if not ps.empty:
        n = ps[ps["model"] == "nmo"]
        if not n.empty:
            cmd("PSRho", _ms(n, "mean_spearman"))
            cmd("PSNull", _val(float(n["mean_null_spearman"].mean())))
            cmd("PSFracPos", f"{100*float(n['frac_positive'].mean()):.0f}")

    # ---- dataset inventory ---------------------------------------------- #
    sp = Path(processed_summary)
    if sp.exists():
        s = json.loads(sp.read_text())
        cmd("NDatasets", str(len(s)))
        cmd("TotalLocations", f"{sum(v['n_obs'] for v in s.values()):,}".replace(",", "{,}"))

    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    return out


if __name__ == "__main__":
    import argparse

    p = argparse.ArgumentParser()
    p.add_argument("--results", default="results")
    p.add_argument("--out", default="paper/numbers.tex")
    a = p.parse_args()
    print(f"wrote {build(a.results, a.out)}")
