"""Emit ``paper/numbers.tex``: every inline number the manuscript quotes.

The paper never hard-codes a result. It uses macros such as ``\\NMOPearson``
that are defined here from the run artifacts, so prose and experiments cannot
diverge. If a run is missing, the macro expands to a visible ``??`` rather than
to a stale value.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from ..models.baselines import DISPLAY_NAMES as DISPLAYNAMES
from .tables import dedupe, is_derived, load_json_glob


def _ms(df: pd.DataFrame, key: str) -> str:
    """mean +/- s.d., wrapped in \\ensuremath so the macro is usable in *both*
    text mode and math mode. Emitting a bare ``$\\pm$`` would close an enclosing
    ``$ ... $`` and break the build wherever the macro appears inside math."""
    if df.empty or key not in df.columns:
        return r"\ensuremath{\mathbf{??}}"
    m, s = df[key].mean(), df[key].std()
    body = f"{m:.3f}" + (f" \\pm {s:.3f}" if np.isfinite(s) and s > 0 else "")
    return f"\\ensuremath{{{body}}}"


def _val(x: Optional[float], prec: int = 3) -> str:
    return r"\ensuremath{\mathbf{??}}" if x is None or not np.isfinite(x) else f"{x:.{prec}f}"


def build(results_root: str | Path = "results", out: str | Path = "paper/numbers.tex",
          processed_summary: str | Path = "data/processed/SUMMARY.json") -> Path:
    results_root = Path(results_root)
    L: List[str] = [
        "% Auto-generated by src/evaluation/numbers.py -- do not edit by hand.",
        r"\providecommand{\NA}{\textbf{??}}",
    ]

    def cmd(name: str, value: str):
        # LaTeX control sequences are letters only. A name like \DistQ1Um parses
        # as \DistQ followed by literal "1Um", which is typesettable material in
        # the preamble, and the resulting "Missing \begin{document}" points at a
        # line that looks perfectly valid.
        if not name.isalpha():
            raise ValueError(
                f"macro name {name!r} is not letters-only; LaTeX would split it")
        L.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    # ---- Experiment 1 : main benchmark ---------------------------------- #
    e1 = pd.DataFrame([r for r in load_json_glob("exp1/**/*.json", results_root)
                       if "model" in r and "pearson_mean" in r])
    if not e1.empty:
        nmo = e1[e1["model"] == "nmo"]
        base = e1[e1["model"] != "nmo"]
        cmd("NMOPearson", _ms(nmo, "pearson_mean"))
        cmd("NMORMSE", _ms(nmo, "rmse"))
        cmd("NMOSSIM", _ms(nmo, "ssim_mean"))
        cmd("NMOMoran", _ms(nmo, "morans_i_abs_error"))
        cmd("NMOParams", f"{nmo['n_params'].mean()/1e6:.2f}M" if "n_params" in nmo else r"\NA")
        cmd("NSeeds", str(int(e1.groupby("model").size().max())))
        if not base.empty:
            g = base.groupby("model")["pearson_mean"].mean().sort_values(ascending=False)
            best_name, best_val = g.index[0], float(g.iloc[0])
            bb = base[base["model"] == best_name]
            cmd("BestBaseline", best_name.replace("_", " "))
            cmd("BestBaselinePearson", _ms(bb, "pearson_mean"))
            cmd("BestBaselineMoran", _ms(bb, "morans_i_abs_error"))
            cmd("BestBaselineSSIM", _ms(bb, "ssim_mean"))
            # Structural metrics: report the best value achieved by ANY baseline,
            # so a weakness of our model cannot hide behind a weak comparator.
            gs = base.groupby("model")["ssim_mean"].mean()
            gm = base.groupby("model")["morans_i_abs_error"].mean()
            cmd("BestAnySSIM", _val(float(gs.max())))
            cmd("BestAnySSIMModel", str(gs.idxmax()).replace("_", " "))
            cmd("BestAnyMoran", _val(float(gm.min())))
            cmd("BestAnyMoranModel", str(gm.idxmin()).replace("_", " "))
            if not nmo.empty:
                cmd("SSIMDelta", _val(float(nmo["ssim_mean"].mean()) - float(gs.max())))
                cmd("MoranDelta", _val(float(nmo["morans_i_abs_error"].mean()) - float(gm.min())))
            nv = float(nmo["pearson_mean"].mean()) if not nmo.empty else np.nan
            cmd("PearsonGain", _val(nv - best_val))
            cmd("PearsonGainPct", _val(100 * (nv - best_val) / max(best_val, 1e-9), 1))
        # Does spatial message passing actually beat plain interpolation? The
        # non-spatial autoencoder shares the same inverse-distance read-out head
        # as every graph baseline, so the difference isolates message passing.
        if (base["model"] == "autoencoder").any():
            ae = float(base[base["model"] == "autoencoder"]["pearson_mean"].mean())
            cmd("AEPearson", _val(ae))
            graphs = ["gnn", "spagcn", "stagate", "graph_transformer"]
            gd = {m: float(base[base["model"] == m]["pearson_mean"].mean()) - ae
                  for m in graphs if (base["model"] == m).any()}
            if gd:
                cmd("BestGraphOverAE", _val(max(gd.values())))
                cmd("WorstGraphOverAE", _val(min(gd.values())))
                cmd("NGraphBelowAE", str(sum(1 for v in gd.values() if v < 0)))
                cmd("NGraphModels", str(len(gd)))
            if not nmo.empty:
                nd = float(nmo["pearson_mean"].mean()) - ae
                cmd("NMOOverAE", _val(nd))
                if gd and max(gd.values()) > 1e-9:
                    cmd("NMOvsGraphRatio", f"{nd / max(gd.values()):.1f}")

        # honest read-out of the over-smoothing diagnostic
        if "morans_i_pred" in e1.columns:
            cmd("NMOMoranPred", _ms(nmo, "morans_i_pred"))
            cmd("MoranTrue", _ms(nmo, "morans_i_true"))

    # ---- operator parameter share --------------------------------------- #
    # Quoted in the parameter-matched control. Hard-coding these in the prose
    # let them drift from the architecture; they are derived here instead.
    try:
        from ..models.nmo import build_nmo
        from ..utils.common import Config as _Cfg
        _c = _Cfg.load("configs/base.yaml")
        _sec_genes = 2079            # visium_mouse_brain, the section of Table 1
        _m = build_nmo(_c.model.to_dict(), n_genes=_sec_genes)
        _tot = sum(p.numel() for p in _m.parameters())
        _dyn = sum(p.numel() for n, p in _m.named_parameters() if n.startswith("operator."))
        cmd("OpParams", f"{_dyn:,}".replace(",", "{,}"))
        cmd("TotalParams", f"{_tot:,}".replace(",", "{,}"))
        cmd("OpParamPct", f"{100 * _dyn / _tot:.2f}")
    except Exception:
        pass

    # ---- Experiment 2 / 3 : transfer ------------------------------------ #
    for tag, pat in [("Tissue", "exp2/**/*.json"), ("Res", "exp3/**/*.json")]:
        df = pd.DataFrame(dedupe([r for r in load_json_glob(pat, results_root) if "setting" in r],
                                 ["model", "seed", "setting", "target"]))
        if df.empty:
            continue
        for setting, suffix in [("zero_shot", "ZeroShot"), ("oracle", "Oracle"),
                                ("floor", "Floor"), ("decoder_finetune", "FineTune")]:
            sub = df[(df["setting"] == setting) & (df["model"].isin(["nmo", "mean"]))]
            if not sub.empty:
                cmd(f"{tag}{suffix}", _ms(sub, "pearson_mean"))
        zs = df[(df["setting"] == "zero_shot")]
        if not zs.empty:
            g = zs.groupby("model")["pearson_mean"].mean().sort_values(ascending=False)
            cmd(f"{tag}ZeroShotBest", str(g.index[0]).replace("_", " "))
            # Baseline comparison under transfer -- reported because NMO loses it.
            base = g.drop(index=[i for i in g.index if i in ("nmo", "mean")], errors="ignore")
            if len(base):
                cmd(f"{tag}ZeroShotBaseline", _ms(
                    zs[zs["model"] == base.index[0]], "pearson_mean"))
                cmd(f"{tag}ZeroShotBaselineName",
                    str(base.index[0]).replace("_", " ") + "-style")
                if (zs["model"] == "nmo").any():
                    nv = float(zs[zs["model"] == "nmo"]["pearson_mean"].mean())
                    cmd(f"{tag}ZeroShotGap", _val(nv - float(base.iloc[0])))
                    cmd(f"{tag}ZeroShotRatio", f"{float(base.iloc[0]) / max(nv, 1e-9):.1f}")
        if "n_shared_genes" in df.columns:
            cmd(f"{tag}SharedGenes", str(int(df["n_shared_genes"].iloc[0])))

    # ---- Experiment 5 : ablations --------------------------------------- #
    e5 = pd.DataFrame(dedupe([r for r in load_json_glob("exp5/**/*.json", results_root) if "variant" in r],
                             ["variant", "seed", "section"]))
    if not e5.empty:
        g = e5.groupby("variant")["pearson_mean"].agg(["mean", "std"])
        full = float(g.loc["full", "mean"]) if "full" in g.index else np.nan
        cmd("AblFull", _val(full))
        for v, name in [("no_dynamics", "AblNoDynamics"), ("no_diffusion", "AblNoDiffusion"),
                        ("no_reaction", "AblNoReaction"), ("no_pde", "AblNoPDE"),
                        ("no_bio_reg", "AblNoBioReg"),
                        ("isotropic_diffusion", "AblIsotropic"),
                        ("discrete_gnn", "AblDiscreteGNN")]:
            if v in g.index:
                cmd(name, _val(float(g.loc[v, "mean"])))
                cmd(name + "Delta", _val(float(g.loc[v, "mean"]) - full))

    # ---- matched-budget controls ----------------------------------------- #
    # The ablation sweep runs at a reduced budget, at which the full model has
    # not converged; that compresses every delta. The two controls carrying the
    # central claim are re-run at exactly the benchmark budget so they can be
    # compared against the NMO row of Table 1 directly.
    m5 = pd.DataFrame(dedupe([r for r in load_json_glob("exp5_matched/**/*.json", results_root)
                              if "variant" in r], ["variant", "seed", "section"]))
    if not m5.empty and not e1.empty:
        nmo_ref = float(e1[e1["model"] == "nmo"]["pearson_mean"].mean())
        cmd("MatchedFull", _val(nmo_ref))
        g = m5.groupby("variant")["pearson_mean"]
        for v, name in [("no_dynamics", "MatchedNoDynamics"), ("no_reaction", "MatchedNoReaction")]:
            if v in g.groups:
                val = float(g.mean()[v])
                cmd(name, _ms(m5[m5["variant"] == v], "pearson_mean"))
                cmd(name + "Delta", _val(val - nmo_ref))
        cmd("MatchedSeeds", str(int(m5.groupby("variant").size().max())))

    # ---- physics diagnostics -------------------------------------------- #
    phys = []
    pj = results_root / "physics.json"
    if pj.exists():
        try:
            phys = json.loads(pj.read_text())
        except Exception:
            phys = []
    for p in sorted(results_root.glob("**/result.json")):
        try:
            r = json.loads(p.read_text())
            if "physics" in r:
                phys.append(r["physics"])
        except Exception:
            continue
    if phys:
        dl = np.concatenate([np.asarray(p["diffusion_length_um"]).ravel() for p in phys
                             if p.get("diffusion_length_um")])
        if dl.size:
            cmd("DiffLenMedian", f"{np.median(dl):.0f}")
            cmd("DiffLenLo", f"{np.percentile(dl, 10):.0f}")
            cmd("DiffLenHi", f"{np.percentile(dl, 90):.0f}")
            # Scope of that spread: it is across latent channels of one section,
            # not across sections or tissues, and the prose must say so.
            per_run = [np.asarray(p["diffusion_length_um"]).ravel().size
                       for p in phys if p.get("diffusion_length_um")]
            cmd("DiffLenN", str(int(dl.size)))
            cmd("DiffLenPerRun", str(int(per_run[0])) if per_run else r"\NA")
            secs = {str(p.get("checkpoint", "")).split("/runs/")[-1].split("__")[0]
                    for p in phys if p.get("checkpoint")}
            secs.discard("")
            cmd("DiffLenSections", str(len(secs)) if secs else r"\NA")
            cmd("DiffLenSection", (sorted(secs)[0].replace("_", r"\_")) if secs else r"\NA")
        wl = [p["pattern_wavelength_um"] for p in phys if p.get("pattern_wavelength_um")]
        cmd("TuringFrac", f"{100*np.mean([bool(p['turing_unstable']) for p in phys]):.0f}")
        cmd("NPhysicsRuns", str(len(phys)))
        gz = [p.get("growth_at_zero") for p in phys if p.get("growth_at_zero") is not None]
        if gz:
            cmd("GrowthAtZero", f"{np.mean(gz):.2f}")
        if wl:
            cmd("PatternWavelength", f"{np.median(wl):.0f}")

    # ---- Experiment 4 ---------------------------------------------------- #
    bead = pd.DataFrame(load_json_glob("exp4/**/bead_implant.json", results_root))
    if not bead.empty:
        sig = bead.groupby("pathway")["p_value"].mean()
        cmd("BeadNSig", str(int((sig < 0.05).sum())))
        cmd("BeadNPathways", str(int(len(sig))))
        cmd("BeadWidth", f"{bead['response_halfwidth_um'].mean():.0f}")
        cmd("BeadMeanRank", f"{bead['held_out_mean_rank_pct'].mean():.0f}")
        cmd("BeadMinP", f"{bead.groupby('pathway')['p_value'].mean().min():.2f}")
        cmd("BeadSeeds", str(int(bead['seed'].nunique())))
    ps = pd.DataFrame([r for r in load_json_glob("exp4/**/perturbseq_consistency.json", results_root)
                       if "error" not in r])
    if not ps.empty:
        n = ps[ps["model"] == "nmo"]
        if not n.empty:
            cmd("PSRho", _ms(n, "mean_spearman"))
            cmd("PSNull", _val(float(n["mean_null_spearman"].mean())))
            cmd("PSFracPos", f"{100*float(n['frac_positive'].mean()):.0f}")
            cmd("PSNPerturb", str(int(n["n_perturbations"].mean())))
            cmd("PSNShared", str(int(n["n_shared_genes"].mean())))
            cmd("PSWilcoxonP", f"{float(n['wilcoxon_p'].mean()):.2f}")

    # ---- Experiment 6 : developmental forecasting ------------------------ #
    dev = pd.DataFrame(load_json_glob("exp6/**/forecast.json", results_root))
    if not dev.empty and "field_pearson_mean" in dev.columns:
        pers = dev[dev["model"] == "persistence"]["field_pearson_mean"]
        if len(pers):
            cmd("DevPersistence", _val(float(pers.mean())))
        nm = dev[dev["model"] == "nmo"]
        if not nm.empty:
            byh = nm.groupby("horizon")["field_pearson_mean"].mean()
            best_h = int(byh.idxmax())
            cmd("DevNMOBest", _val(float(byh.max())))
            cmd("DevNMOBestHorizon", str(best_h))
            z = byh.get(0)
            if z is not None:
                cmd("DevNMOZero", _val(float(z)))
            if len(pers):
                cmd("DevBeatsPersistence",
                    "yes" if float(byh.max()) > float(pers.mean()) else "no")

    # ---- Experiment 8 : multi-section benchmark -------------------------- #
    from .statistics import MIN_HELDOUT_LOCATIONS as _MINHO
    ms = [x for f in Path(results_root).glob("exp8/results_shard*.json")
          for x in json.loads(f.read_text()) if "pearson_mean" in x and not x.get("failed")]
    # Sections whose held-out set is too small to estimate Pearson r are
    # excluded; see statistics.MIN_HELDOUT_LOCATIONS for the rule and why it is
    # fixed independently of the outcome.
    _excluded = sorted({x["section"] for x in ms
                        if x.get("n_obs_used", 10 ** 9) < 4 * _MINHO})
    ms = [x for x in ms if x.get("n_obs_used", 10 ** 9) >= 4 * _MINHO]
    if _excluded:
        cmd("MSExcludedN", str(len(_excluded)))
        cmd("MSExcluded", ", ".join(e.replace("_", r"\_") for e in _excluded))
        cmd("MSMinHeldOut", str(_MINHO))
    if ms:
        from .statistics import paired_comparison as _pc
        m8 = pd.DataFrame(ms)
        cmd("MSRuns", str(len(m8)))
        cmd("MSSeeds", str(int(m8.groupby(["section", "model"]).size().max())))
        per = m8.groupby(["section", "model"])["pearson_mean"].mean().unstack("model")
        # Every aggregate is taken over the sections on which NMO actually ran.
        # Averaging each model over whatever sections it happens to cover makes
        # the marginal means incomparable and disagree with the paired test.
        matched = per.dropna(subset=["nmo"])
        cmd("MSSections", str(int(len(matched))))
        cmd("MSPool", str(int(per.shape[0])))
        cmd("MSNMOPearson", _val(float(matched["nmo"].mean())))
        res = _pc(m8, "nmo", "pearson_mean")
        if res:
            best = min(res, key=lambda r: r.mean_diff)          # closest competitor
            worst = max(res, key=lambda r: r.mean_diff)         # weakest comparator
            cmd("MSBestBaseline", DISPLAYNAMES.get(best.other, best.other))
            cmd("MSBestBaselinePearson", _val(float(matched[best.other].mean())))
            cmd("MSMinDelta", _val(best.mean_diff))
            cmd("MSWeakest", DISPLAYNAMES.get(worst.other, worst.other))
            cmd("MSWeakestPearson", _val(float(matched[worst.other].mean())))
            cmd("MSMaxDelta", _val(worst.mean_diff))            # A9: the weakest model's gap
            cmd("MSMinDz", f"{best.cohens_dz:.2f}")
            cmd("MSMaxHolm", f"{max(r.p_holm for r in res):.1g}")
            # Baselines can cover different numbers of sections, so a bare
            # "wins on W of N" would pair a win count from one comparison with
            # the section count of another. Report the weakest win *fraction*
            # as an explicit w/n, and the range of n alongside it.
            worst_frac = min(res, key=lambda r: r.n_reference_wins / max(r.n_sections, 1))
            cmd("MSMinWins", f"{worst_frac.n_reference_wins}")
            cmd("MSMinWinFrac",
                f"{worst_frac.n_reference_wins}/{worst_frac.n_sections}")
            ns = sorted({r.n_sections for r in res})
            cmd("MSNPairs", str(ns[-1]))
            cmd("MSNPairsRange", str(ns[0]) if len(ns) == 1 else f"{ns[0]}--{ns[-1]}")
            cmd("MSNBaselines", str(len(res)))
            cmd("MSAllSig", "yes" if all(r.p_holm < 0.05 for r in res) else "no")

        # Structural metrics at the benchmark's own scope. The single-section
        # equivalents (\NMOSSIM, \BestAnySSIM, ...) describe results/exp1 and
        # must not be quoted in prose about this benchmark.
        for key, tag, lower_better in [("ssim_mean", "SSIM", False),
                                       ("morans_i_abs_error", "Moran", True),
                                       ("rmse", "RMSE", True)]:
            if key not in m8.columns:
                continue
            pm = m8.groupby(["section", "model"])[key].mean().unstack("model").loc[matched.index]
            cmd(f"MSNMO{tag}", _val(float(pm["nmo"].mean())))
            others = pm.drop(columns=["nmo"], errors="ignore").mean()
            others = others.dropna()
            if len(others):
                bi = others.idxmin() if lower_better else others.idxmax()
                cmd(f"MSBestAny{tag}", _val(float(others[bi])))
                cmd(f"MSBestAny{tag}Model", DISPLAYNAMES.get(bi, bi))
                cmd(f"MS{tag}Delta", _val(float(pm["nmo"].mean()) - float(others[bi])))

        # How much of each margin could be optimisation noise. The within-section
        # across-seed s.d. is the floor below which a difference between models
        # is not distinguishable from a rerun.
        sdev = m8.groupby(["section", "model"])["pearson_mean"].std().groupby(
            "model").median()
        if "nmo" in sdev.index:
            cmd("SeedSDNMO", _val(float(sdev["nmo"]), 4))
            cmd("SeedSDMax", _val(float(sdev.max()), 4))
            cmd("SeedSDMaxModel", DISPLAYNAMES.get(sdev.idxmax(), sdev.idxmax()))
            ratios = {}
            # Restrict to models the benchmark table actually shows: including a
            # baseline dropped for coverage would let its very large margin set
            # the top of the reported range.
            shown = {m for m in matched.columns
                     if int(matched[m].notna().sum()) >= max(3, int(0.9 * len(matched)))}
            for other in sdev.index:
                if other == "nmo" or other not in shown:
                    continue
                delta = float(matched["nmo"].mean()) - float(matched[other].mean())
                noise = float(np.hypot(sdev["nmo"], sdev[other]))
                if noise > 0:
                    ratios[other] = delta / noise
            if ratios:
                lo = min(ratios, key=ratios.get)
                cmd("SeedRatioLo", f"{ratios[lo]:.1f}")
                cmd("SeedRatioLoModel", DISPLAYNAMES.get(lo, lo))
                cmd("SeedRatioHi", f"{max(ratios.values()):.1f}")

        # Message-passing isolation, recomputed at this benchmark's scope.
        if "autoencoder" in matched.columns:
            ae = float(matched["autoencoder"].mean())
            cmd("MSAEPearson", _val(ae))
            gd = {m: float(matched[m].mean()) - ae
                  for m in ["gnn", "spagcn", "stagate", "graph_transformer"]
                  if m in matched.columns}
            if gd:
                cmd("MSBestGraphOverAE", _val(max(gd.values())))
                cmd("MSWorstGraphOverAE", _val(min(gd.values())))
                cmd("MSNGraphModels", str(len(gd)))
            cmd("MSNMOOverAE", _val(float(matched["nmo"].mean()) - ae))
        # Specimen-level (conservative) analysis: serial sections of one brain
        # are not independent samples, so this is the defensible unit.
        from .statistics import by_specimen as _bs, min_attainable_p as _map
        sp = _bs(m8)
        res2 = _pc(sp, "nmo", "pearson_mean")
        cmd("MSSpecimens", str(int(sp["section"].nunique())))
        if res2:
            cmd("MSSpecPairs", str(res2[0].n_sections))
            cmd("MSSpecMinP", f"{_map(res2[0].n_sections):.2f}")
            graphs = [r for r in res2 if r.other in ("gnn", "stagate", "autoencoder")]
            cont = [r for r in res2 if r.other in ("neural_field", "gp_multiscale")]
            # Family-wise correction has a floor set jointly by the number of
            # specimens and the number of comparisons; quoting an uncorrected p
            # without it would overstate what the design can resolve.
            if res2:
                cmd("MSSpecUncorrP", f"{min(r.wilcoxon_p for r in res2):.4f}")
                cmd("MSSpecHolmFloor", f"{_map(res2[0].n_sections) * len(res2):.3f}")
                # Baselines separated after family-wise correction: the claim
                # the design could not previously express at any effect size.
                # Sensitivity to the one debatable grouping choice: the two
                # Stereo-seq stages are different embryos but the same series,
                # and the paper counts them once. Reported so a reader can see
                # the conclusion does not depend on it.
                try:
                    from .statistics import SPECIMEN_OF as _SO
                    _alt = {k: v for k, v in _SO.items() if k != "mosta_embryo"}

                    def _spec_alt(sec: str) -> str:
                        for pre, nm in _alt.items():
                            if sec.startswith(pre):
                                return nm
                        return sec
                    _a = m8.copy()
                    _a["section"] = _a["section"].map(_spec_alt)
                    _a = _a.groupby(["section", "model"], as_index=False)["pearson_mean"].mean()
                    _ra = _pc(_a, "nmo", "pearson_mean")
                    cmd("MSSpecAltN", str(_ra[0].n_sections) if _ra else r"\NA")
                    cmd("MSSpecAltNSig",
                        str(sum(1 for r in _ra if r.p_holm < 0.05)))
                except Exception:
                    pass
                sig = [r for r in res2 if r.p_holm < 0.05 and r.n_sections >= 8]
                cmd("MSSpecNSig", str(len(sig)))
                if sig:
                    cmd("MSSpecSigMaxHolm", f"{max(r.p_holm for r in sig):.3f}")
                    _tight = min(sig, key=lambda r: r.mean_diff)
                    cmd("MSSpecTightModel", DISPLAYNAMES.get(_tight.other, _tight.other))
                    cmd("MSSpecTightDelta", _val(_tight.mean_diff))
                    cmd("MSSpecTightCI",
                        f"[{_tight.ci_lo:+.4f}, {_tight.ci_hi:+.4f}]")
                    cmd("MSSpecSigMinWins",
                        f"{min(r.n_reference_wins for r in sig)}/{sig[0].n_sections}")
                    cmd("MSSpecSigModels",
                        ", ".join(DISPLAYNAMES.get(r.other, r.other)
                                  for r in sorted(sig, key=lambda r: r.p_holm)))
                    graph_sig = [r for r in sig if r.other in ("gnn", "stagate",
                                                               "autoencoder")]
                    cmd("MSSpecGraphSig",
                        DISPLAYNAMES.get(graph_sig[0].other, graph_sig[0].other)
                        if graph_sig else "none")
                    if graph_sig:
                        cmd("MSSpecGraphSigHolm", f"{graph_sig[0].p_holm:.3f}")
                        cmd("MSSpecGraphSigWins",
                            f"{graph_sig[0].n_reference_wins}/{graph_sig[0].n_sections}")
                sweeps = [r for r in res2
                          if r.n_reference_wins == r.n_sections and r.n_sections >= 8]
                cmd("MSSpecSweeps", str(len(sweeps)))
                if sweeps:
                    cmd("MSSpecSweepDz", f"{min(r.cohens_dz for r in sweeps):.2f}")
                gr = [r for r in graphs if r.n_sections >= 8]
                if gr:
                    worst = max(gr, key=lambda r: r.wilcoxon_p)
                    cmd("MSSpecGraphWorstP", f"{worst.wilcoxon_p:.2f}")
                    cmd("MSSpecGraphWorstModel",
                        DISPLAYNAMES.get(worst.other, worst.other))
                    cmd("MSSpecGraphWins",
                        f"{min(r.n_reference_wins for r in gr)}/{gr[0].n_sections}")
            if graphs:
                cmd("MSSpecGraphDz", f"{min(r.cohens_dz for r in graphs):.2f}"
                    + "--" + f"{max(r.cohens_dz for r in graphs):.2f}")
                cmd("MSSpecGraphDelta", _val(min(r.mean_diff for r in graphs)))
            if cont:
                cmd("MSSpecContDz", f"{min(r.cohens_dz for r in cont):.2f}")
                cmd("MSSpecContDelta", _val(min(r.mean_diff for r in cont)))
            cmd("MSSpecWins", f"{min(r.n_reference_wins for r in res2)}")

    # ---- Experiment 9 : biology ------------------------------------------ #
    bp = Path(results_root) / "exp9" / "biology.json"
    if bp.exists():
        b = pd.DataFrame([r for r in json.loads(bp.read_text()) if "ari_predicted" in r])
        if not b.empty:
            # Two exclusions, for the same reason as the benchmark: a section
            # too small to estimate the metric, and a reference clustering too
            # weak for a ratio to mean anything.
            from .statistics import (MIN_REFERENCE_ARI as _MINARI,
                                     MIN_HELDOUT_LOCATIONS as _MINHO2)
            if "ari_measured" in b.columns:
                _drop = sorted(set(b.loc[b["ari_measured"] < _MINARI, "section"]))
                b = b[b["ari_measured"] >= _MINARI]
                if _drop:
                    cmd("BioExcluded", ", ".join(d.replace("_", r"\_") for d in _drop))
                    cmd("BioExcludedN", str(len(_drop)))
                    cmd("BioMinARI", f"{_MINARI:g}")
        if not b.empty:
            cmd("BioSections", str(int(b["section"].nunique())))
            # With seven annotated sections the biology comparison is testable,
            # which it was not at four. Report the paired test rather than
            # margins the reader has to eyeball against their own dispersion.
            from .statistics import paired_comparison as _pcb
            rb = _pcb(b, "nmo", "ari_retention", section_col="section")
            for r_ in rb:
                if r_.other == "stagate":
                    cmd("BioARIStagateD", _val(r_.mean_diff))
                    cmd("BioARIStagateDz", f"{r_.cohens_dz:.2f}")
                    cmd("BioARIStagateP", f"{r_.wilcoxon_p:.3f}")
                    cmd("BioARIStagateWins", f"{r_.n_reference_wins}/{r_.n_sections}")
            sig = [r_ for r_ in rb if r_.wilcoxon_p < 0.05]
            cmd("BioARINSig", str(len(sig)))
            cmd("BioARINComp", str(len(rb)))
            g = b.groupby("model")
            for k, nm in [("ari_retention", "BioARIRet"), ("marker_auroc_predicted", "BioMarker"),
                          ("neighborhood_preservation", "BioKNN")]:
                if k in b.columns:
                    # These margins are a fraction of their own spread, so the
                    # dispersion travels with every quoted mean.
                    cmd(nm, _ms(b[b["model"] == "nmo"], k))
                    cmd(nm + "Mean", _val(float(g[k].mean().get("nmo", np.nan))))
                    others = g[k].mean().drop(index=["nmo"], errors="ignore")
                    if len(others):
                        top = others.idxmax()
                        cmd(nm + "Best", _ms(b[b["model"] == top], k))
                        cmd(nm + "BestMean", _val(float(others.max())))
                        cmd(nm + "BestModel", DISPLAYNAMES.get(top, top))
                        # margin expressed in units of the pooled s.d. across
                        # sections: the honest read of how large it is.
                        sd = float(pd.concat([b[b["model"] == "nmo"][k],
                                              b[b["model"] == top][k]]).std())
                        gap = float(g[k].mean().get("nmo", np.nan)) - float(others.max())
                        cmd(nm + "Gap", _val(gap))
                        cmd(nm + "GapSD", _val(gap / sd, 2) if sd > 0 else r"\NA")

